let lang = 'en';
try {
  const forced = new URLSearchParams(location.search).get('lang');
  const nav = (navigator.language || 'en').toLowerCase();
  lang = forced && STR[forced] ? forced : nav.startsWith('de') ? 'de' : 'en';
} catch { /* keep default */ }

export const getLang = () => lang;
export const t = (key) => STR[lang][key] ?? STR.en[key] ?? key;
// Pick the right language from a `{de, en}` object (used by hero data).
export const tr = (obj) => (typeof obj === 'string' ? obj : obj[lang] ?? obj.en);
